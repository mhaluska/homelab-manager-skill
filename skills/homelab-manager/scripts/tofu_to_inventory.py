#!/usr/bin/env python3
"""Generate ansible/inventory/managed/tofu_hosts.yml from the OpenTofu `ansible_hosts` output.

    python3 tofu_to_inventory.py [--env homelab | --site NAME]   # S3 state: prefix with_secrets.py <state secret> --

The generated file is committed; hand-maintained hosts stay in hosts.yml. The default environment writes
tofu_hosts.yml, any other tofu_hosts-<env>.yml; a site's environment (--site) also puts every host into the
group site_<name>, so patching and plays treat them as hosts of that site.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hmlib  # noqa: E402


def to_yaml(groups: dict[str, dict], env: str = "", site_group: str = "") -> str:
    src = f"`tofu output ansible_hosts` ({env})" if env else "`tofu output ansible_hosts`"
    lines = [f"# GENERATED by tofu_to_inventory.py from {src} — do not edit.", "all:", "  children:"]
    for g in sorted(groups):
        lines.append(f"    {g}:")
        lines.append("      hosts:")
        for h, v in sorted(groups[g].items()):
            lines.append(f"        {h}:")
            for k, val in v.items():
                if val is not None:
                    lines.append(f"          {k}: {json.dumps(val)}")
    names = sorted({h for g in groups.values() for h in g})
    if site_group and names:   # the hosts' location: patching snapshots them on that site's Proxmox
        lines += [f"    {site_group}:", "      hosts:"] + [f"        {h}:" for h in names]
    if len(lines) == 3:
        lines[-1] = "  children: {}"
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--env")
    g.add_argument("--site", help="the site's environment (sites: in homelab.yaml)")
    a = ap.parse_args()
    try:
        cfg = hmlib.load_config()
        env = a.env or hmlib.tofu_env(cfg, a.site)
        st = hmlib.site_of_env(cfg, env)
    except hmlib.ConfigError as e:
        print(f"tofu_to_inventory: {e}", file=sys.stderr)
        return 3
    root = Path(cfg["_root"])
    default = env == hmlib.default_env(cfg)
    r = subprocess.run(["tofu", "output", "-json", "ansible_hosts"], cwd=root / "tofu" / "environments" / env,
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr.strip(), file=sys.stderr)
        return r.returncode
    hosts = json.loads(r.stdout or "{}")
    groups: dict[str, dict] = {}
    for name, h in hosts.items():
        hv = {"ansible_host": h.get("ansible_host"), "proxmox_vmid": h.get("vm_id"), "proxmox_node": h.get("node"),
              "proxmox_kind": h.get("kind")}
        for g in (h.get("groups") or ["ungrouped_tofu"]):
            groups.setdefault(g, {})[name] = hv
    out = root / "ansible" / "inventory" / "managed" / ("tofu_hosts.yml" if default else f"tofu_hosts-{env}.yml")
    site_group = hmlib.SITE_GROUP_PREFIX + st["name"] if st["name"] else ""   # a named default site too (#64)
    hmlib.atomic_write(out, to_yaml(groups, "" if default else env, site_group))
    print(f"Wrote {out.relative_to(root)}: {len(hosts)} host(s) in {len(groups)} group(s)")
    missing = [n for n, h in hosts.items() if not h.get("ansible_host")]
    if missing:
        print("No IP yet (DHCP, guest agent not reporting): " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Generate ansible/inventory/managed/tofu_hosts.yml from the OpenTofu `ansible_hosts` output.

    with_secrets.py gitlab-state -- python3 tofu_to_inventory.py [--env homelab]

The generated file is committed; hand-maintained hosts stay in hosts.yml.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hmlib  # noqa: E402


def to_yaml(groups: dict[str, dict]) -> str:
    lines = ["# GENERATED by tofu_to_inventory.py from `tofu output ansible_hosts` — do not edit.", "all:", "  children:"]
    for g in sorted(groups):
        lines.append(f"    {g}:")
        lines.append("      hosts:")
        for h, v in sorted(groups[g].items()):
            lines.append(f"        {h}:")
            for k, val in v.items():
                if val is not None:
                    lines.append(f"          {k}: {json.dumps(val)}")
    if not groups:
        lines[-1] = "  children: {}"
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--env")
    a = ap.parse_args()
    cfg = hmlib.load_config()
    root = Path(cfg["_root"])
    env = a.env or hmlib.get(cfg, "opentofu.environment", "homelab")
    r = subprocess.run(["tofu", "output", "-json", "ansible_hosts"], cwd=root / "tofu" / "environments" / env,
                       capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stderr.strip(), file=sys.stderr)
        return r.returncode
    hosts = json.loads(r.stdout or "{}")
    groups: dict[str, dict] = {}
    for name, h in hosts.items():
        hv = {"ansible_host": h.get("ansible_host"), "proxmox_vmid": h.get("vm_id"), "proxmox_node": h.get("node"),
              "proxmox_kind": h.get("kind")}
        for g in (h.get("groups") or ["ungrouped_tofu"]):
            groups.setdefault(g, {})[name] = hv
    out = root / "ansible" / "inventory" / "managed" / "tofu_hosts.yml"
    out.write_text(to_yaml(groups))
    print(f"Wrote {out.relative_to(root)}: {len(hosts)} host(s) in {len(groups)} group(s)")
    missing = [n for n, h in hosts.items() if not h.get("ansible_host")]
    if missing:
        print("No IP yet (DHCP, guest agent not reporting): " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
